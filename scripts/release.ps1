<# Prints the explicit manual release checklist. It changes no remote state. #>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Push-Location $root
try {
    $version = (Select-String -Path Directory.Build.props -Pattern '<Version>([^<]+)</Version>').Matches.Groups[1].Value
    if ($version -notmatch '^\d{2}\.\d{4}\.\d{4}$') { throw "Version '$version' must use YY.MMDD.HHmm." }
    [DateTime]::ParseExact($version, 'yy.MMdd.HHmm', [Globalization.CultureInfo]::InvariantCulture) | Out-Null
    $branch = git branch --show-current
    $dirty = git status --porcelain
    Write-Host "StreamsPlayer release checklist for v$version" -ForegroundColor Cyan
    Write-Host "Branch: $branch"
    if ($dirty) { Write-Warning 'Working tree is not clean.' }
    Write-Host @"

1. Confirm all intended changes are committed on main and CI is green.
2. Prepare the release tree, then commit it:
   - Set a new local-time (Europe/Malta) ``YY.MMDD.HHmm`` value in every version field in
     Directory.Build.props, then write the What's new blocks into msix/store-listing.md and
     msix/listing/release-notes/<version>.{en-us,ru,uk}.txt. Confirm the stamp is greater than every
     published version, on every channel - stamps at or below 26.0806.2131 were UTC and read 1-2 h early,
     and the Store has shipped a stamp of its own (26.0806.2225) that GitHub and winget never carried.
     Check it: ./scripts/assert-release-version.ps1 -Version <version>  (release.yml runs the same gate).
   - Write the release manifest the site's download buttons render from (SP-0259, PAGE-STYLE 3.10):
     ./tools/site/Write-ReleaseManifest.ps1 -Version <version>  (it refuses a version without notes).
   - Regenerate the site (tools/site/build-site.ps1) so What's new lists the version and the landing
     links its assets; it ships with the release push and deploys only after release.yml succeeded.
   - Regenerate the bundled catalog snapshot and verify it:
     ./tools/build-catalog-snapshot.ps1  and  ./tools/build-catalog-snapshot.ps1 -Check
     A snapshot that is missing, over its size ceiling, or older than the bank currently published
     blocks the release. Never pass -Offline here: it skips exactly that last comparison.
   - README.md carries no version and must not gain one: the READMEs link /releases/latest. docs/ is
     generated by tools/site/build-site.ps1, its version comes only from tools/site/release-manifest.json,
     and hand-editing it is reverted by the next run. Every surface a user-visible change must reach - its source, its generator and
     its languages - is listed once in DOCS_SURFACES.md; walk it before committing.
3. Run: ./scripts/check.ps1
   Then the final code audit (SP-0180), on the exact candidate, once its code is complete:
   - Run the audit campaign of docs/agent/CODE_AUDIT.md over the candidate and resolve every High and
     Medium finding (fix it, or record the owner's explicit decision to ship with it). Commit the fixes,
     re-run ./scripts/check.ps1 on the result.
   - On a clean committed tree write the verdict from your findings file:
     ./scripts/Write-AuditVerdict.ps1 -FindingsPath <findings.json>   and commit
     release-verdicts/<version>.audit.json. The writer refuses an unresolved High/Medium finding; release.yml
     runs ./scripts/Assert-AuditVerdict.ps1 and refuses a verdict whose audited commit is followed by any
     change outside release-verdicts/ - after a material change, audit again.
4. Run: ./scripts/smoke-playback.ps1
   Publishes the committed tree, then plays a live radio station and a live video stream through the
   shipping binary. Red here blocks the release outright. check.ps1 cannot cover this and never
   could: it exercises this repository's code, and SP-0093 was a defect in the WPF runtime
   underneath it - 858 tests stayed green while the product played nothing and a release shipped.
   A build that plays is the only evidence that it plays. A PASS on a clean tree writes
   release-verdicts/<version>.json (SP-0156); a red run writes nothing.
4b. Read the Store's live state before the tag, read-only: ./scripts/Invoke-StorePreflight.ps1
   It calls the shared preflight of the sza plugin with the Store ID from msix/identity.json and the MSIX
   form of this version, and stops here (exit 1, do not tag) when a submission is pending, the version is
   not greater than every live package, the price is not Free, or the product has no live submission.
   When the channel is unconfigured, the credential is missing or expired, or the token is refused, it prints
   one line that the Store step is manual and exits 0: the release goes on exactly as without it, and the
   channel never fails a release after the tag. Pass -CredentialExpiry <date> from your expiry list so an
   expired credential reads as manual. It tests none of: the package signature (the package is built after
   the tag; the read-back of item 6 and 10 judges it), Store-managed consumables, a console edit of a
   submission, or that a write would succeed - it writes nothing. It appends one line per run (no account
   identifier, no credential) to release-verdicts/<version>.store-preflight.jsonl; commit that file in item 5.
5. Commit the verdict file release-verdicts/<version>.json and the Store preflight record
   release-verdicts/<version>.store-preflight.jsonl, then tag the commit locally:
   git tag v<version>
   The verdict must sit inside the tagged tree - release.yml refuses to build without it, and it must
   name exactly the tagged version. Do not push the tag yet.
6. Build and locally test the package: ./msix/build-msix.ps1 -SelfSign
   The script takes the version from the tag at HEAD and refuses a dirty tree or a HEAD off the tag
   (SP-0156). Trust its test certificate, install the package, launch it.
7. Push the tag only after explicit release approval. release.yml then requires a green CI run for the
   tagged commit (the fast tier since SP-0256), the committed smoke verdict for the tagged version, and the
   pinned natives in the payload; an already published asset is never replaced with different bytes
   (SP-0156). On the tag's own tree it runs the documentation gate, the build, the test suite, the
   test-verdict and Store listing fixtures and the site-sync check (SP-0256). It reads the version back
   from the staged exe, the exe inside the zip and the setup EXE (SP-0247).
8. Verify the four assets release.yml generated: the zip, the
   *-windows-x64-setup.exe installer, and a SHA256 sidecar for each. Then run
   the installer on a machine that does not already have it - a published
   installer nobody has executed is an unverified one, and it is the only
   asset that can leave a broken install behind.
9. The Pages publish of item 11 must be live BEFORE the winget (9) and Store (10) submissions: the
   winget templates and msix/store-listing.md now point their support address at the site's support
   page (support.html, ru/, uk/), so confirm those addresses answer 200 on the host first.
   Render the release's manifests from the tag - never type the version:
   ./winget/New-WingetManifests.ps1 -Tag v<version> -OutputDirectory temp/winget/<version> -InstallerSha256 <hash> ..
   (winget/README.md), copy them to winget-pkgs, validate them, and submit its pull request.
10. Build the unsigned Store package at the tag: ./msix/build-msix.ps1 (no -SelfSign), upload it,
    update Store listing text/screenshots, then submit for certification.
    The same submission also updates the Partner Center Properties support URL and support e-mail
    from the Support and Support email lines of msix/store-listing.md - the package alone does not
    carry them.
    The upload itself stays manual. The read-only preflight of item 4b has already read the live state;
    msstore submission status 9NBTD5SXB8TB shows it again (a pending submission and the live package).
    Never run a writing msstore command without the owner's words naming the product and the package
    version - STORE_PUBLISHING.md, Phase 7.
11. GitHub Pages deploys when the release.yml run of item 7 concludes success, never on a push: pages.yml
    runs the documentation gate and the site-sync check on the commit it publishes, then deploys that
    commit (SP-0156, SP-0256). To publish the site at another time, run it explicitly:
    gh workflow run pages.yml. Confirm the site is ready for public visibility. Items 9 and 10 wait for
    this deploy to be live.

This command does not tag, push, upload, submit, or publish anything.
"@
}
finally { Pop-Location }
